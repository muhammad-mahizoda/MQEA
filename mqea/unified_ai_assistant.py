    def _analyze_conversation_context(self, query: str, analysis: Dict[str, Any]) -> Dict[str, Any]:
        """Анализ контекста разговора."""
        context_info = {
            'topic_continuation': False,
            'topic_shift': False,
            'entity_continuation': False,
            'preference_inference': None,
            'conversation_stage': 'beginning'
        }
        
        try:
            # Анализируем текущую тему
            current_intent = analysis.get('intent', 'unknown')
            
            # Проверяем продолжение темы
            if self.conversation_context['current_topic'] == current_intent:
                context_info['topic_continuation'] = True
            elif self.conversation_context['current_topic'] is not None:
                context_info['topic_shift'] = True
            
            # Обновляем текущую тему
            if current_intent != 'unknown':
                self.conversation_context['current_topic'] = current_intent
                self.conversation_context['topic_history'].append(current_intent)
                
                # Ограничиваем историю тем
                if len(self.conversation_context['topic_history']) > 10:
                    self.conversation_context['topic_history'] = self.conversation_context['topic_history'][-10:]
            
            # Извлекаем сущности из запроса
            entities = self._extract_entities(query)
            if entities:
                context_info['entity_continuation'] = any(
                    entity in self.conversation_context['recent_entities'] 
                    for entity in entities
                )
                self.conversation_context['recent_entities'].extend(entities)
                
                # Ограничиваем список сущностей
                if len(self.conversation_context['recent_entities']) > 20:
                    self.conversation_context['recent_entities'] = self.conversation_context['recent_entities'][-20:]
            
            # Определяем стадию разговора
            query_count = len(self.conversation_history)
            if query_count == 0:
                context_info['conversation_stage'] = 'greeting'
            elif query_count < 3:
                context_info['conversation_stage'] = 'beginning'
            elif query_count < 10:
                context_info['conversation_stage'] = 'middle'
            else:
                context_info['conversation_stage'] = 'advanced'
            
            # Анализируем предпочтения пользователя
            context_info['preference_inference'] = self._infer_user_preferences(query, analysis)
            
            # Обновляем поток разговора
            self.conversation_context['conversation_flow'].append({
                'query': query,
                'intent': current_intent,
                'context': context_info.copy(),
                'timestamp': datetime.now().isoformat()
            })
            
            # Ограничиваем поток разговора
            if len(self.conversation_context['conversation_flow']) > 50:
                self.conversation_context['conversation_flow'] = self.conversation_context['conversation_flow'][-50:]
                
        except Exception as e:
            print(f"Ошибка анализа контекста: {e}")
        
        return context_info
    
