    def _initialize_ml_models(self):
        """Инициализация ML моделей."""
        try:
            # Загружаем сохраненные модели, если они есть
            self._load_ml_models()
        except:
            # Если модели не найдены, создаем новые
            self._create_initial_ml_models()
    
    def _load_ml_models(self):
        """Загрузка сохраненных ML моделей."""
        model_dir = "mqea_models"
        if not os.path.exists(model_dir):
            os.makedirs(model_dir)
            
        try:
            # Загружаем векторизатор
            if os.path.exists(f"{model_dir}/vectorizer.pkl"):
                with open(f"{model_dir}/vectorizer.pkl", 'rb') as f:
                    self.vectorizer = pickle.load(f)
            
            # Загружаем кластеры
            if os.path.exists(f"{model_dir}/clusters.pkl"):
                with open(f"{model_dir}/clusters.pkl", 'rb') as f:
                    self.query_clusters = pickle.load(f)
            
            # Загружаем модель схожести
            if os.path.exists(f"{model_dir}/similarity_model.pkl"):
                with open(f"{model_dir}/similarity_model.pkl", 'rb') as f:
                    self.similarity_model = pickle.load(f)
            
        except Exception as e:
            print(f"Ошибка загрузки ML моделей: {e}")
            self._create_initial_ml_models()
    
    def _create_initial_ml_models(self):
        """Создание начальных ML моделей."""
        # Создаем обучающие данные из базы знаний
        training_data = []
        labels = []
        
        for category, data in self.knowledge_base.items():
            for pattern in data['patterns']:
                # Преобразуем паттерны в обучающие примеры
                training_data.append(pattern)
                labels.append(category)
        
        # Добавляем дополнительные примеры
        additional_examples = [
            ("привет как дела", "greetings"),
            ("что такое mqea", "mqea_concepts"),
            ("объясни квантовую запутанность", "quantum_concepts"),
            ("какие нормальные показатели пульса", "medical_indicators"),
            ("как интерпретировать результаты анализа", "analysis_help"),
            ("дай медицинские рекомендации", "recommendations"),
            ("помоги с диагностикой", "diagnosis_help"),
            ("расскажи про лекарства", "medications"),
            ("спасибо за помощь", "thanks"),
            ("до свидания", "goodbye")
        ]
        
        for example, label in additional_examples:
            training_data.append(example)
            labels.append(label)
        
        # Обучаем векторизатор
        try:
            self.vectorizer.fit(training_data)
            
            # Создаем кластеры для похожих запросов
            if len(training_data) > 3:
                vectors = self.vectorizer.transform(training_data)
                n_clusters = min(len(set(labels)), 5)  # Максимум 5 кластеров
                self.query_clusters = KMeans(n_clusters=n_clusters, random_state=42)
                self.query_clusters.fit(vectors)
            
            # Сохраняем модели
            self._save_ml_models()
            
        except Exception as e:
            print(f"Ошибка создания ML моделей: {e}")
    
    def _save_ml_models(self):
        """Сохранение ML моделей."""
        model_dir = "mqea_models"
        if not os.path.exists(model_dir):
            os.makedirs(model_dir)
        
        try:
            # Сохраняем векторизатор
            with open(f"{model_dir}/vectorizer.pkl", 'wb') as f:
                pickle.dump(self.vectorizer, f)
            
            # Сохраняем кластеры
            if self.query_clusters is not None:
                with open(f"{model_dir}/clusters.pkl", 'wb') as f:
                    pickle.dump(self.query_clusters, f)
            
            # Сохраняем модель схожести
            if self.similarity_model is not None:
                with open(f"{model_dir}/similarity_model.pkl", 'wb') as f:
                    pickle.dump(self.similarity_model, f)
                    
        except Exception as e:
            print(f"Ошибка сохранения ML моделей: {e}")
    
    def _predict_intent_ml(self, query: str) -> Dict[str, Any]:
        """Предсказание намерения с помощью ML."""
        try:
            # Проверяем, что векторизатор обучен
            if not hasattr(self.vectorizer, 'vocabulary_') or not self.vectorizer.vocabulary_:
                return {
                    'intent': 'unknown',
                    'confidence': 0.0,
                    'cluster_id': None,
                    'ml_prediction': False
                }
            
            # Векторизуем запрос
            query_vector = self.vectorizer.transform([query])
            
            # Определяем кластер
            cluster_id = None
            if self.query_clusters is not None:
                cluster_id = self.query_clusters.predict(query_vector)[0]
            
            # Находим наиболее похожие запросы в базе знаний
            similarities = {}
            for category, data in self.knowledge_base.items():
                for pattern in data['patterns']:
                    pattern_vector = self.vectorizer.transform([pattern])
                    similarity = cosine_similarity(query_vector, pattern_vector)[0][0]
                    if category not in similarities or similarity > similarities[category]:
                        similarities[category] = similarity
            
            # Выбираем категорию с наибольшей схожестью
            if similarities:
                best_category = max(similarities, key=similarities.get)
                confidence = similarities[best_category]
                
                return {
                    'intent': best_category,
                    'confidence': confidence,
                    'cluster_id': cluster_id,
                    'ml_prediction': True
                }
            
        except Exception as e:
            print(f"Ошибка ML предсказания: {e}")
        
        return {
            'intent': 'unknown',
            'confidence': 0.0,
            'cluster_id': None,
            'ml_prediction': False
        }
    
    def _learn_from_interaction(self, query: str, response: str, user_feedback: str = None):
        """Обучение на основе взаимодействия."""
        try:
            # Добавляем в данные обучения
            self.add_learning_data(query, response, user_feedback)
            
            # Переобучаем модели каждые 10 новых запросов
            if len(self.learning_data) % 10 == 0:
                self._retrain_models()
                
        except Exception as e:
            print(f"Ошибка обучения: {e}")
    
    def _retrain_models(self):
        """Переобучение ML моделей."""
        try:
            if len(self.learning_data) < 5:
                return
            
            # Подготавливаем данные для переобучения
            queries = [item['query'] for item in self.learning_data[-50:]]  # Последние 50 запросов
            
            # Обновляем векторизатор
            self.vectorizer.fit(queries)
            
            # Переобучаем кластеры
            if len(queries) > 3:
                vectors = self.vectorizer.transform(queries)
                n_clusters = min(len(queries) // 10, 5)  # Адаптивное количество кластеров
                if n_clusters > 1:
                    self.query_clusters = KMeans(n_clusters=n_clusters, random_state=42)
                    self.query_clusters.fit(vectors)
            
            # Сохраняем обновленные модели
            self._save_ml_models()
            
            # Обновляем статистику
            self.stats['learning_events'] += 1
            
        except Exception as e:
            print(f"Ошибка переобучения: {e}")
    
    def process_query(self, query: str) -> str:
        """Обработка запроса пользователя."""
        self.stats['total_queries'] += 1
        self.stats['last_interaction'] = datetime.now().isoformat()
        
        # Добавляем в историю
        self.conversation_history.append({
            'timestamp': datetime.now().isoformat(),
            'user_query': query,
            'response': None  # Будет заполнено после генерации ответа
        })
        
        # Анализируем запрос (комбинируем традиционный и ML подходы)
        analysis = self._analyze_query(query)
        ml_analysis = self._predict_intent_ml(query)
        
        # Объединяем результаты анализа
        if ml_analysis['ml_prediction'] and ml_analysis['confidence'] > analysis['confidence']:
            analysis.update(ml_analysis)
        
        # Анализируем контекст разговора
        context = self._analyze_conversation_context(query, analysis)
        
        # Генерируем ответ
        response = self._generate_response(query, analysis)
        
        # Контекстуализируем ответ
        response = self._contextualize_response(response, context)
        
        # Обновляем историю
        self.conversation_history[-1]['response'] = response
        
        # Обновляем статистику
        if response and not response.startswith("❌"):
            self.stats['successful_answers'] += 1
            if ml_analysis['ml_prediction']:
                self.stats['ml_predictions'] += 1
        
        # Обучение на основе взаимодействия
        self._learn_from_interaction(query, response)
        
        return response
    
    def _analyze_query(self, query: str) -> Dict[str, Any]:
        """Анализ запроса пользователя."""
        query_lower = query.lower().strip()
        
        analysis = {
            'intent': 'unknown',
            'confidence': 0.0,
            'keywords': [],
            'category': 'general',
            'context': query_lower
        }
        
        # Определяем намерение
        for category, data in self.knowledge_base.items():
            for pattern in data['patterns']:
                if re.search(pattern, query_lower):
                    analysis['intent'] = category
                    analysis['confidence'] = 0.8
                    analysis['category'] = category
                    break
            if analysis['intent'] != 'unknown':
                break
        
        # Извлекаем ключевые слова
        keywords = []
        for word in query_lower.split():
            if len(word) > 3 and word not in ['что', 'как', 'где', 'когда', 'почему', 'зачем']:
                keywords.append(word)
        analysis['keywords'] = keywords
        
        return analysis
    
    def _generate_response(self, query: str, analysis: Dict[str, Any]) -> str:
        """Генерация ответа на основе анализа."""
        try:
            intent = analysis['intent']
            
            if intent in self.knowledge_base:
                responses = self.knowledge_base[intent]['responses']
                # Выбираем случайный ответ из доступных
                response = random.choice(responses)
                
                # Добавляем персонализацию
                response = self._personalize_response(response, analysis)
                
                return response
            else:
                # Если намерение не определено, пробуем найти по ключевым словам
                return self._handle_unknown_query(query, analysis)
                
        except Exception as e:
            return f"❌ Ошибка обработки запроса: {str(e)}"
    
    def _personalize_response(self, response: str, analysis: Dict[str, Any]) -> str:
        """Персонализация ответа."""
        personalized_response = response
        
        # Добавляем контекстную информацию
        if analysis.get('keywords'):
            # Упоминаем ключевые слова, если они релевантны
            if len(analysis['keywords']) > 0:
                keywords_str = ", ".join(analysis['keywords'][:3])  # Первые 3 ключевых слова
                personalized_response += f"\n\n🔍 *По ключевым словам: {keywords_str}*"
        
