    def _infer_user_preferences(self, query: str, analysis: Dict[str, Any]) -> Dict[str, Any]:
        """Вывод предпочтений пользователя."""
        preferences = {}
        
        # Анализируем предпочтения по темам
        intent = analysis.get('intent', 'unknown')
        if intent != 'unknown':
            preferences['preferred_topics'] = preferences.get('preferred_topics', [])
            if intent not in preferences['preferred_topics']:
                preferences['preferred_topics'].append(intent)
        
        # Анализируем уровень детализации
        if len(query.split()) > 5:
            preferences['detail_level'] = 'detailed'
        elif len(query.split()) > 2:
            preferences['detail_level'] = 'medium'
        else:
            preferences['detail_level'] = 'brief'
        
        # Анализируем язык
        russian_words = ['что', 'как', 'где', 'когда', 'почему', 'привет', 'спасибо']
        english_words = ['what', 'how', 'where', 'when', 'why', 'hello', 'thanks']
        
        russian_count = sum(1 for word in russian_words if word in query.lower())
        english_count = sum(1 for word in english_words if word in query.lower())
        
        if russian_count > english_count:
            preferences['language'] = 'russian'
        elif english_count > russian_count:
            preferences['language'] = 'english'
        else:
            preferences['language'] = 'mixed'
        
        return preferences
    
    def _contextualize_response(self, response: str, context: Dict[str, Any]) -> str:
        """Контекстуализация ответа на основе анализа разговора."""
        contextualized_response = response
        
        try:
            # Добавляем информацию о продолжении темы
            if context.get('topic_continuation', False):
                contextualized_response = f"📌 *Продолжая тему...*\n\n{contextualized_response}"
            
            # Добавляем информацию о смене темы
            if context.get('topic_shift', False):
                contextualized_response = f"🔄 *Переходя к новой теме...*\n\n{contextualized_response}"
            
            # Адаптируем под стадию разговора
            stage = context.get('conversation_stage', 'beginning')
            if stage == 'greeting':
                contextualized_response = f"👋 {contextualized_response}"
            elif stage == 'beginning':
                contextualized_response = f"🌱 {contextualized_response}"
            elif stage == 'middle':
                contextualized_response = f"💡 {contextualized_response}"
            elif stage == 'advanced':
                contextualized_response = f"🎯 {contextualized_response}"
            
            # Адаптируем под предпочтения пользователя
            preferences = context.get('preference_inference', {})
            detail_level = preferences.get('detail_level', 'medium')
            
            if detail_level == 'brief' and len(contextualized_response) > 200:
                # Сокращаем ответ для пользователей, предпочитающих краткость
                sentences = contextualized_response.split('. ')
                contextualized_response = '. '.join(sentences[:2]) + '.'
                if len(sentences) > 2:
                    contextualized_response += '\n\n💡 *Нужно больше деталей? Спросите!*'
            
            # Добавляем информацию о контексте
            if context.get('entity_continuation', False):
                contextualized_response += '\n\n🔗 *Связано с предыдущими вопросами*'
            
        except Exception as e:
            print(f"Ошибка контекстуализации: {e}")
        
        return contextualized_response
    
