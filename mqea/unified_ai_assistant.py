        context_info = self.get_conversation_context()
        if context_info['current_topic']:
            personalized_response += f"\n\n🎯 *Текущая тема: {context_info['current_topic']}*"
        if context_info['conversation_length'] > 1:
            personalized_response += f"\n\n📊 *Длина разговора: {context_info['conversation_length']} сообщений*"
        
        return personalized_response
    
