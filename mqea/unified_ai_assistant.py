    def get_similar_queries(self, query: str, limit: int = 5) -> List[Dict[str, Any]]:
        """Поиск похожих запросов в истории."""
        try:
            if not self.conversation_history:
                return []
            
            # Проверяем, что векторизатор обучен
            if not hasattr(self.vectorizer, 'vocabulary_') or not self.vectorizer.vocabulary_:
                return []
            
            # Векторизуем текущий запрос
            query_vector = self.vectorizer.transform([query])
            
            similarities = []
            for item in self.conversation_history[-20:]:  # Последние 20 запросов
                if item['user_query']:
                    hist_vector = self.vectorizer.transform([item['user_query']])
                    similarity = cosine_similarity(query_vector, hist_vector)[0][0]
                    similarities.append({
                        'query': item['user_query'],
                        'similarity': similarity,
                        'timestamp': item.get('timestamp', '')
                    })
            
            # Сортируем по схожести и возвращаем топ
            similarities.sort(key=lambda x: x['similarity'], reverse=True)
            return similarities[:limit]
            
        except Exception as e:
            print(f"Ошибка поиска похожих запросов: {e}")
            return []
    
    def analyze_conversation_patterns(self) -> Dict[str, Any]:
        """Анализ паттернов в разговоре."""
        try:
            if len(self.conversation_history) < 3:
                return {'message': 'Недостаточно данных для анализа'}
            
            # Анализируем частоту тем
            topic_counts = {}
            for item in self.conversation_history:
                query = item.get('user_query', '').lower()
                for category, data in self.knowledge_base.items():
                    for pattern in data['patterns']:
                        if re.search(pattern, query):
                            topic_counts[category] = topic_counts.get(category, 0) + 1
                            break
            
            # Находим наиболее популярные темы
            popular_topics = sorted(topic_counts.items(), key=lambda x: x[1], reverse=True)[:5]
            
            # Анализируем временные паттерны
            time_analysis = {
                'total_queries': len(self.conversation_history),
                'popular_topics': popular_topics,
                'avg_query_length': np.mean([len(item.get('user_query', '').split()) for item in self.conversation_history]),
                'ml_usage_rate': (self.stats['ml_predictions'] / max(self.stats['total_queries'], 1)) * 100
            }
            
            return time_analysis
            
        except Exception as e:
            print(f"Ошибка анализа паттернов: {e}")
            return {'error': str(e)}
    
