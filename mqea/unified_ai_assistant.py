    def _improve_response_pattern(self, query: str, response: str, feedback: str = None):
        """Улучшение паттернов ответов на основе низкого качества."""
        try:
            # Анализируем запрос и находим проблемные области
            query_lower = query.lower()
            
            # Ищем категорию, которая дала плохой ответ
            problem_category = None
            for category, data in self.knowledge_base.items():
                for pattern in data['patterns']:
                    if re.search(pattern, query_lower):
                        problem_category = category
                        break
                if problem_category:
                    break
            
            # Если нашли проблемную категорию, добавляем новый паттерн
            if problem_category and feedback:
                # Добавляем новый паттерн на основе запроса
                new_pattern = self._extract_pattern_from_query(query)
                if new_pattern and new_pattern not in self.knowledge_base[problem_category]['patterns']:
                    self.knowledge_base[problem_category]['patterns'].append(new_pattern)
                    
                    # Сохраняем улучшения
                    self._save_knowledge_base()
                    
        except Exception as e:
            print(f"Ошибка улучшения паттерна: {e}")
    
    def _extract_pattern_from_query(self, query: str) -> str:
        """Извлечение паттерна из запроса."""
        # Упрощенное извлечение ключевых слов как паттерн
        words = query.lower().split()
        # Берем слова длиннее 3 символов, исключая стоп-слова
        stop_words = {'что', 'как', 'где', 'когда', 'почему', 'зачем', 'для', 'это', 'все', 'мне'}
        key_words = [word for word in words if len(word) > 3 and word not in stop_words]
        
        if key_words:
            return r'\b' + r'\b.*\b'.join(key_words[:3]) + r'\b'  # Максимум 3 ключевых слова
        return None
    
