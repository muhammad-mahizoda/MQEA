    def add_learning_data(self, query: str, response: str, feedback: str = None):
        """Добавление данных для обучения."""
        learning_entry = {
            'timestamp': datetime.now().isoformat(),
            'query': query,
            'response': response,
            'feedback': feedback,
            'quality_score': self._calculate_response_quality(response, feedback)
        }
        
        self.learning_data.append(learning_entry)
        self.stats['learning_events'] += 1
        
        # Автоматическое обучение на основе качества ответа
        if learning_entry['quality_score'] < 0.7:
            self._improve_response_pattern(query, response, feedback)
    
    def _calculate_response_quality(self, response: str, feedback: str = None) -> float:
        """Вычисление качества ответа."""
        quality_score = 0.5  # Базовый балл
        
        # Анализируем длину ответа
        if len(response) > 100:
            quality_score += 0.2
        
        # Проверяем наличие структуры (заголовки, списки)
        if any(marker in response for marker in ['**', '•', '-', '1.', '2.']):
            quality_score += 0.2
        
        # Проверяем наличие эмодзи (указывает на персонализацию)
        if any(emoji in response for emoji in ['🤖', '📊', '🔍', '💡', '⚛️']):
            quality_score += 0.1
        
        # Анализируем обратную связь
        if feedback:
            if any(word in feedback.lower() for word in ['хорошо', 'отлично', 'спасибо', 'помогло']):
                quality_score += 0.3
            elif any(word in feedback.lower() for word in ['плохо', 'не помогло', 'неправильно']):
                quality_score -= 0.3
        
        # Проверяем, что ответ не является ошибкой
        if response.startswith("❌"):
            quality_score = 0.0
        
